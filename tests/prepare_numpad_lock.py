"""Build this checkout's core RCC in an independent runtime snapshot."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from native_qml_resources import create_snapshot, verify_snapshot

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-snapshot", type=Path, required=True)
    parser.add_argument("--core-qrc", type=Path, required=True,
                        help="core.qrc generated by CMake for this checkout")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error("Output must be a new directory")
    verify_snapshot(args.base_snapshot)
    qrc = args.core_qrc.read_bytes()
    private = args.output.resolve() / "runtime"
    shutil.copytree(args.base_snapshot, private)
    rcc = private / "share/gcompris-qt/rcc/core.rcc"
    subprocess.run(["/usr/lib/qt6/libexec/rcc", "--format-version", "2",
                    "--compress-algo", "zlib", "--no-zstd", "-binary",
                    "-o", str(rcc), "-"], cwd=ROOT / "src/core", input=qrc, check=True)
    create_snapshot(private / "bin/gcompris-qt", args.output / "snapshot")
    metadata = {"qrc_sha256": hashlib.sha256(qrc).hexdigest(),
                "NumPad_source_sha256": hashlib.sha256((ROOT / "src/core/NumPad.qml").read_bytes()).hexdigest(),
                "core_rcc_sha256": hashlib.sha256(rcc.read_bytes()).hexdigest()}
    (args.output / "core-build.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(args.output.resolve() / "snapshot")

if __name__ == "__main__":
    main()
